import { buildApp } from '/home/yams/ai-factory/server/src/app.ts';
const { app } = await buildApp();
const boot = await app.inject({ url: '/api/bootstrap' });
console.log('bootstrap', boot.statusCode, JSON.parse(boot.body).stages.room.length);
const rooms = await app.inject({ url: '/api/rooms?phase=present' });
const rj = JSON.parse(rooms.body);
console.log('present rooms', rooms.statusCode, rj.length, rj.map((r: any) => r.name).join(' | '));
const detail = await app.inject({ url: '/api/rooms/wlby' });
const dj = JSON.parse(detail.body);
console.log('wlby', detail.statusCode, dj.room.status, JSON.stringify(dj.room.summary), dj.clusters.length, JSON.stringify(dj.risk));
const clusters = await app.inject({ url: '/api/clusters' });
console.log('clusters', JSON.parse(clusters.body).length);
const csv = await app.inject({ url: '/api/export/clusters.csv?area=cn' });
console.log('csv', csv.statusCode, csv.headers['content-type'], JSON.stringify(csv.body.slice(0, 30)));
const bad = await app.inject({ method: 'POST', url: '/api/rooms', payload: { name: 'Seed WLBY 机房' } });
console.log('dup', bad.statusCode, bad.body);
const created = await app.inject({ method: 'POST', url: '/api/rooms', headers: { 'x-operator': '测试' }, payload: { name: '测试机房', area: 'cn', fields: { 'ko-plan': '2026-12-01' } } });
console.log('create', created.statusCode);
await app.close();
